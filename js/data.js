// ひらがなはカタカナに寄せる（人文字の字形データがカタカナしかないため）
export function toKatakana(s) {
  return s.replace(/[ぁ-ゖ]/g, function (c) {
    return String.fromCharCode(c.charCodeAt(0) + 0x60);
  });
}

// 自由入力を1タイルぶんずつに切り分ける。'!?' だけは2文字で1タイル。
// 同じ文字を複数回書くとその文字が出やすくなる（重み付けとして意図的に残す）。
export function parseFreeChars(str) {
  var s = toKatakana(String(str || '')).replace(/\s/g, '');
  var out = [];
  for (var i = 0; i < s.length; i++) {
    var two = s.substr(i, 2);
    if (two === '!?' || two === '！？') { out.push('!?'); i++; continue; }
    out.push(s[i]);
  }
  return out;
}

export function shuffle(a) {
  for (var i = a.length - 1; i > 0; i--) {
    var j = Math.floor(Math.random() * (i + 1));
    var t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}

// 見立ての揺れを吸収（ォ→オ、二→ニ）
export function normalize(ch) {
  if (ch === 'ォ') return 'オ';
  if (ch === '二') return 'ニ';
  return ch;
}

// 語を「タイル1枚ぶん」の単位に分解する（'!?' は1トークン）
export function tokenize(word) {
  var out = [];
  for (var i = 0; i < word.length; i++) {
    var two = word.substr(i, 2);
    if (two === '!?' || two === '！？') { out.push('!?'); i++; continue; }
    out.push(normalize(word[i]));
  }
  return out;
}

